import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import type { Activation, Exec, ServiceBackend, UnitSpec } from './types.js'

export const UNIT = 'limn'

const unitPath = (): string => path.join(process.env.XDG_CONFIG_HOME || path.join(os.homedir(), '.config'), 'systemd', 'user', `${UNIT}.service`)

export function parseShow(text: string): { active: boolean; pid: number | null } {
  const active = /^ActiveState=(\S+)/m.exec(text)?.[1] === 'active'
  const pid = Number(/^MainPID=(\d+)/m.exec(text)?.[1] ?? 0)
  return { active, pid: pid > 0 ? pid : null }
}

/** systemd's quoted `Environment=` form: an unquoted value is split on whitespace and
 *  `%` starts a specifier, so quote it, escape `\` and `"`, and double the `%`. */
function envLine(key: string, value: string): string {
  const escaped = value.replace(/\\/g, '\\\\').replace(/"/g, '\\"').replace(/%/g, '%%')
  return `Environment="${key}=${escaped}"\n`
}

function renderUnit(spec: UnitSpec): string {
  const extraEnv = Object.entries(spec.extraEnv).map(([k, v]) => envLine(k, v)).join('')
  return `# Limn background service (generated by \`limn service install\`; re-run it to repair).
# After \`npm i -g @glebmish/limn@latest\`: systemctl --user restart ${UNIT}
# Stop: systemctl --user stop ${UNIT}   Remove: limn service uninstall
[Unit]
Description=Limn — agentic local branch review
After=network.target

[Service]
ExecStart=${spec.nodePath} ${spec.entryPath} service serve${spec.port80 ? ' --port-80' : ''}
Restart=always
RestartSec=2
${envLine('PATH', spec.pathEnv)}${envLine('HOME', spec.home)}${extraEnv}StandardOutput=append:${spec.logFile}
StandardError=append:${spec.logFile}

[Install]
WantedBy=default.target
`
}

export const systemd: ServiceBackend = {
  name: 'systemd',
  unitPath,
  renderUnit,
  async install(spec, run) {
    const file = unitPath()
    fs.mkdirSync(path.dirname(file), { recursive: true })
    fs.mkdirSync(path.dirname(spec.logFile), { recursive: true })
    // 0600: the unit records LIMN_WEB_TOKEN verbatim, and the default 0644 would put
    // it in reach of every account on the machine. chmod after the write too — an
    // existing file keeps its old mode, so `mode` alone does not repair a 0644 unit.
    fs.writeFileSync(file, renderUnit(spec), { mode: 0o600 })
    fs.chmodSync(file, 0o600)
    const reload = await run('systemctl', ['--user', 'daemon-reload'])
    if (reload.code !== 0) throw new Error(`systemctl daemon-reload failed: ${reload.stderr.trim()}`)
    const en = await run('systemctl', ['--user', 'enable', '--now', UNIT])
    if (en.code !== 0) throw new Error(`systemctl enable --now failed: ${en.stderr.trim()}`)
    await run('systemctl', ['--user', 'restart', UNIT])
  },
  async uninstall(run) {
    await run('systemctl', ['--user', 'disable', '--now', UNIT])
    fs.rmSync(unitPath(), { force: true })
    await run('systemctl', ['--user', 'daemon-reload'])
  },
  async activation(run: Exec): Promise<Activation> {
    const file = unitPath()
    if (!fs.existsSync(file)) return { kind: 'service', loaded: false, unitPath: file }
    const res = await run('systemctl', ['--user', 'show', UNIT, '-p', 'ActiveState', '-p', 'MainPID'])
    const { active, pid } = parseShow(res.stdout)
    const nodePath = /^ExecStart=(\S+)/m.exec(fs.readFileSync(file, 'utf8'))?.[1] ?? ''
    let nodeOk = false
    try { fs.accessSync(nodePath, fs.constants.X_OK); nodeOk = true } catch { /* missing */ }
    return { kind: 'service', loaded: true, running: active, pid, unitPath: file, nodePath, nodeOk, restartCmd: `systemctl --user restart ${UNIT}`, stopCmd: `systemctl --user stop ${UNIT}` }
  }
}
